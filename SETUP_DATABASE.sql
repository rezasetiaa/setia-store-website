-- Sebelum menjalankan di proyek lama, periksa tabel yang sudah ada agar tidak menimpa data.
create extension if not exists pgcrypto;

create table if not exists public.customer_orders (
  id uuid primary key default gen_random_uuid(),
  order_code text unique not null default ('SS-' || upper(substr(encode(gen_random_bytes(6),'hex'),1,10))),
  created_at timestamptz not null default now(),
  customer_name text not null,
  phone text not null,
  email text,
  fulfillment text not null default 'pickup' check (fulfillment in ('pickup','delivery')),
  address text not null default '',
  notes text not null default '',
  items jsonb not null,
  total_amount bigint not null check (total_amount >= 0),
  currency text not null default 'IDR',
  payment_method text not null default 'gateway',
  payment_status text not null default 'Menunggu' check (payment_status in ('Menunggu','Menunggu konfirmasi','Dibayar','Gagal','Dikembalikan')),
  status text not null default 'Baru' check (status in ('Baru','Dikonfirmasi','Diproses','Siap diambil','Dikirim','Selesai','Dibatalkan')),
  payment_reference text,
  updated_at timestamptz not null default now()
);

create table if not exists public.products (
  id bigint generated by default as identity primary key,
  name text not null,
  category text not null default 'Gift & Souvenir',
  description text not null default '',
  price bigint not null default 0 check (price >= 0),
  display_price text not null default '',
  image_url text,
  active boolean not null default true,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.product_reviews (
  id uuid primary key default gen_random_uuid(),
  order_id uuid not null references public.customer_orders(id) on delete cascade,
  product_id bigint references public.products(id) on delete set null,
  customer_name text not null,
  rating int not null check (rating between 1 and 5),
  review_text text not null default '',
  photo_url text,
  is_verified boolean not null default false,
  is_published boolean not null default false,
  created_at timestamptz not null default now(),
  unique(order_id, product_id)
);

create table if not exists public.admin_users (
  user_id uuid primary key references auth.users(id) on delete cascade,
  created_at timestamptz not null default now()
);

alter table public.customer_orders enable row level security;
alter table public.products enable row level security;
alter table public.product_reviews enable row level security;
alter table public.admin_users enable row level security;

-- Public hanya bisa membuat pesanan; tidak dapat membaca semua pesanan customer.
drop policy if exists "public_create_orders" on public.customer_orders;
create policy "public_create_orders" on public.customer_orders for insert to anon, authenticated
with check (
  status = 'Baru' and payment_status in ('Menunggu','Menunggu konfirmasi')
  and length(trim(customer_name)) between 1 and 100
  and length(trim(phone)) between 6 and 25
);

-- Produk aktif dan ulasan terbit bisa dibaca publik.
drop policy if exists "public_read_active_products" on public.products;
create policy "public_read_active_products" on public.products for select to anon, authenticated using (active = true);
drop policy if exists "public_read_published_reviews" on public.product_reviews;
create policy "public_read_published_reviews" on public.product_reviews for select to anon, authenticated using (is_published = true);

-- Hanya akun yang tercatat di admin_users boleh melihat/mengubah pesanan dan mengelola produk/ulasan.
drop policy if exists "admin_read_orders" on public.customer_orders;
create policy "admin_read_orders" on public.customer_orders for select to authenticated
using (exists(select 1 from public.admin_users a where a.user_id = auth.uid()));
drop policy if exists "admin_update_orders" on public.customer_orders;
create policy "admin_update_orders" on public.customer_orders for update to authenticated
using (exists(select 1 from public.admin_users a where a.user_id = auth.uid()))
with check (exists(select 1 from public.admin_users a where a.user_id = auth.uid()));

drop policy if exists "admin_manage_products" on public.products;
create policy "admin_manage_products" on public.products for all to authenticated
using (exists(select 1 from public.admin_users a where a.user_id = auth.uid()))
with check (exists(select 1 from public.admin_users a where a.user_id = auth.uid()));

drop policy if exists "admin_manage_reviews" on public.product_reviews;
create policy "admin_manage_reviews" on public.product_reviews for all to authenticated
using (exists(select 1 from public.admin_users a where a.user_id = auth.uid()))
with check (exists(select 1 from public.admin_users a where a.user_id = auth.uid()));

drop policy if exists "admin_read_admin_users" on public.admin_users;
create policy "admin_read_admin_users" on public.admin_users for select to authenticated
using (user_id = auth.uid());

